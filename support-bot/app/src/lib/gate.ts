// 호출 전 검사 — 모델을 부르기 **전에** 프로그램이 막는다.
//
// 왜 지시문이 아니라 여기인가.
// 프롬프트에 "개인 데이터를 조회하지 않는다"고 적어 두었는데, G 에서 재 보니
// "제 있템이 지금 몇 개예요?" 의 거부가 3회 중 참·거짓·참으로 흔들렸다.
// 검색 점수로도 걸러지지 않는다 — 이 질문의 점수(0.648)가 답할 수 있는
// 질문들과 같은 띠에 있다.
//
// 4강 실습에서 같은 것을 봤다. "추측 금지" 를 설명문에 적어도 모델은 없는
// 코드를 발명했고, 문제를 0건으로 만든 것은 지시문이 아니라 호출 전 검사였다.
// 그래서 이 규칙은 모델에게 부탁하지 않는다.
//
// 규칙(정규식)은 dev-bot 에서 그대로 가져왔다 — 통과해야 할 질문 13개와
// 막아야 할 질문 8개로 검증된 것이라 다시 만들 이유가 없다.
// **답변 문구만 고객센터 말투로 바꿨다.**
//
// 막는 범위는 PRD 3절이 비목표로 못 박은 것뿐이다. "자료에 없는 주제" 전체를
// 여기서 막지 않는다 — 그건 낱말로 셀 수 있는 것이 아니고, 그 판단은 근거를
// 읽어야 나온다. 게이트는 **셀 수 있는 것만** 맡는다.

export type GateRule = "개인 데이터 조회" | "계정·비밀번호 대행" | "상태 변경 대행";

export type GateResult =
  | { blocked: false }
  | { blocked: true; rule: GateRule; matched: string; answer: string };

/** 「어떻게 …하나요」처럼 방법을 묻는 문장인가. 이러면 막지 않는다. */
const ASKS_HOW = /어떻게|어디서|어디에|어디로|무슨 뜻|방법|하나요|되나요|인가요|있나요|가능한가요|되나\?|어떤/;

/** 1인칭 소유 표현 */
const MINE = /(^|[\s,.?!])(제|내|나의|저의|우리)\s*(?=\S)|제것|내것|내 것/;

/** 이 서비스의 데이터를 가리키는 말 */
const MY_DATA = /있템|위시|쓴템|보유템|물건|재고|아이템|항목|목록/;

/** 개수·목록을 묻는 말 */
const ASKS_COUNT = /몇\s*개|개수|얼마나|몇\s*건|얼마야|얼만큼|목록|뭐가?\s*있|무엇이\s*있|보여\s*줘|알려\s*줘/;

/** 계정·비밀번호 관련 말 */
const ACCOUNT = /비밀번호|패스워드|닉네임|이메일 주소|계정|약관|탈퇴|회원\s*정보/;

/** 대신 해 달라는 말 */
const DO_IT_FOR_ME = /해\s*줘|해\s*주세요|해줘|바꿔\s*줘|바꿔줘|변경해|재설정해|발송해|보내\s*줘|보내줘|지워\s*줘|지워줘|삭제해|옮겨\s*줘|옮겨줘|등록해\s*줘|취소해/;

const ANSWERS: Record<GateRule, string> = {
  "개인 데이터 조회":
    "죄송하지만 **고객님 계정 안의 정보는 확인해 드릴 수 없습니다.** 이 상담 창구는 공개된 도움말만 읽고, 로그인이나 계정 접근을 하지 않습니다.\n\n" +
    "직접 확인하시려면 [이미 있어](https://already-got-it.vercel.app)에 로그인하신 뒤 목록 화면을 열어 주세요.\n\n" +
    "대신 이런 것은 안내해 드릴 수 있습니다 — 있템을 등록하는 방법, 쓴템 탭이 무엇인지, D-day 배지가 무슨 뜻인지.",
  "계정·비밀번호 대행":
    "죄송하지만 **계정이나 비밀번호를 대신 조작해 드리지는 않습니다.** 재설정 메일을 보내거나, 닉네임을 바꾸거나, 약관에 동의해 드리지 않습니다.\n\n" +
    "비밀번호를 잊으셨다면 로그인 화면의 「비밀번호를 잊으셨나요?」를 눌러 재설정 메일을 받아 주세요.\n\n" +
    "그 절차가 어떻게 되는지는 도움말을 근거로 안내해 드릴 수 있습니다. 「비밀번호 재설정은 어떻게 하나요?」라고 물어봐 주세요.",
  "상태 변경 대행":
    "죄송하지만 **데이터를 대신 바꿔 드리지는 않습니다.** 위시를 있템으로 옮기거나, 상태를 바꾸거나, 항목을 지워 드리지 않습니다.\n\n" +
    "이런 동작은 되돌리기 어려워서, 고객님이 앱 화면에서 직접 누르시도록 남겨 두었습니다.\n\n" +
    "「어떻게 옮기나요?」처럼 **방법**을 물어봐 주시면 도움말을 근거로 순서대로 안내해 드립니다.",
};

/**
 * 모델을 부르기 전에 검사한다. 막히면 모델을 아예 부르지 않는다.
 *
 * 막지 않는 것: 방법을 묻는 질문. "위시에 담아둔 걸 샀는데 어떻게 옮겨요?" 는
 * 대신 해 달라는 말이 아니라 절차를 묻는 말이다.
 */
export function checkBeforeCall(question: string): GateResult {
  const q = question.trim();
  const asksHow = ASKS_HOW.test(q);

  // 1. 개인 데이터 조회 — 내 것 + 데이터 + 개수/목록
  if (MINE.test(q) && MY_DATA.test(q) && ASKS_COUNT.test(q)) {
    return { blocked: true, rule: "개인 데이터 조회", matched: "1인칭 소유 + 내 데이터 + 개수·목록", answer: ANSWERS["개인 데이터 조회"] };
  }

  // 2. 계정·비밀번호 대행 — 방법을 묻는 것이면 막지 않는다
  if (ACCOUNT.test(q) && DO_IT_FOR_ME.test(q) && !asksHow) {
    return { blocked: true, rule: "계정·비밀번호 대행", matched: "계정·비밀번호 + 대신 해 달라는 요청", answer: ANSWERS["계정·비밀번호 대행"] };
  }

  // 3. 상태 변경 대행 — 역시 방법을 묻는 것이면 막지 않는다
  if (MY_DATA.test(q) && DO_IT_FOR_ME.test(q) && !asksHow) {
    return { blocked: true, rule: "상태 변경 대행", matched: "내 데이터 + 대신 해 달라는 요청", answer: ANSWERS["상태 변경 대행"] };
  }

  return { blocked: false };
}
